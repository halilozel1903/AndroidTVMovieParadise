package com.halil.ozel.movieparadise.data.models;

public class Video {

    private String id;
    private String key;
    private String site;
    private String type;
    private String name;

    public Video() {
    }

    public String getKey() {
        return key;
    }

    public String getSite() {
        return site;
    }

    public String getType() {
        return type;
    }

    public String getName() {
        return name;
    }
}
